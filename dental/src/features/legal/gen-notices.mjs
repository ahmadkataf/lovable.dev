// Writes src/features/legal/notices.ts: the open-source notices shown in Settings → About → Open-source licences.
// Run it after adding, removing or upgrading a runtime dependency (tests/settings-legal.test.ts fails until you do):
//   node src/features/legal/gen-notices.mjs
// Every package that ends up in the app (the "dependencies" of package.json and the libraries they bring into the
// bundle) is listed with its version, licence, copyright lines and the full licence text, read from node_modules.
// Identical licence bodies are stored once. Dexie's Apache-2.0 NOTICE file is reproduced as §4(d) requires.
import { readFileSync, writeFileSync, readdirSync, existsSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '../../..')
const pkg = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8'))
// libraries the bundle carries without being listed in package.json
const BUNDLED = { 'react-dom': ['scheduler'], 'react-router-dom': ['react-router'], 'react-router': ['cookie', 'set-cookie-parser'] }

const names = []
const add = n => { if (!names.includes(n)) { names.push(n); for (const d of BUNDLED[n] ?? []) add(d) } }
for (const n of Object.keys(pkg.dependencies ?? {}).sort()) add(n)

const texts = []          // unique licence bodies
const notices = []
for (const name of names) {
  const dir = join(root, 'node_modules', name)
  const meta = JSON.parse(readFileSync(join(dir, 'package.json'), 'utf8'))
  const file = readdirSync(dir).find(f => /^licen[cs]e(\.md|\.txt)?$/i.test(f))
  if (!file) throw new Error(`no licence file in ${name}`)
  const raw = readFileSync(join(dir, file), 'utf8').replace(/\r\n/g, '\n').trim()
  const font = meta.license === 'OFL-1.1'
  let copyright, body
  if (font) {
    // fontsource: the first paragraph is the font's copyright statement, then the OFL text
    const cut = raw.indexOf('\n\n')
    copyright = raw.slice(0, cut).split(/\s(?=\S+\.ttf:)/).map(s => s.trim()).filter(Boolean).slice(0, 1)
    body = raw.slice(cut).trim()
  } else if (meta.license === 'Apache-2.0') {
    // the Apache text is kept whole; the copyright comes from the NOTICE file, else from the package author
    const noticeFile = readdirSync(dir).find(f => /^notice(\.md|\.txt)?$/i.test(f))
    const fromNotice = noticeFile ? readFileSync(join(dir, noticeFile), 'utf8').split('\n').filter(l => /^\s*Copyright\b/.test(l)).map(l => l.trim()) : []
    const author = typeof meta.author === 'string' ? meta.author : meta.author?.name
    copyright = fromNotice.length ? fromNotice : author ? [`Copyright (c) ${author}`] : []
    body = raw
  } else {
    // MIT / ISC: the copyright lines start with "Copyright"; the permission text is the body
    const lines = raw.split('\n')
    const isCopyright = l => /^\s*Copyright\b/.test(l)
    copyright = lines.filter(isCopyright).map(l => l.trim())
    body = lines.filter(l => !isCopyright(l)).join('\n').replace(/\n{3,}/g, '\n\n').trim()
  }
  let textId = texts.findIndex(t => t === body)
  if (textId < 0) { texts.push(body); textId = texts.length - 1 }
  const noticeFile = readdirSync(dir).find(f => /^notice(\.md|\.txt)?$/i.test(f))
  const repo = typeof meta.repository === 'string' ? meta.repository : meta.repository?.url
  const url = (meta.homepage || repo || '').replace(/^git\+/, '').replace(/\.git$/, '').replace(/^(\w[\w-]*\/[\w.-]+)$/, 'https://github.com/$1')
  notices.push({
    name, version: meta.version, license: meta.license, url, copyright, text: textId,
    ...(noticeFile ? { notice: readFileSync(join(dir, noticeFile), 'utf8').replace(/\r\n/g, '\n').trim() } : {}),
    ...(font ? { kind: 'font' } : {}),
  })
}

const out = `// Generated by src/features/legal/gen-notices.mjs from node_modules — do not edit by hand; run the script instead.
// The open-source software and fonts inside Dentora, with their licences (shown in Settings → About).
export interface Notice { name: string; version: string; license: string; url: string; copyright: string[]; text: number; notice?: string; kind?: 'font' }
export const NOTICES: Notice[] = ${JSON.stringify(notices, null, 2)}
/** Licence bodies, by Notice.text. */
export const LICENSE_TEXTS: string[] = ${JSON.stringify(texts, null, 2)}
`
writeFileSync(join(root, 'src/features/legal/notices.ts'), out)
console.log(`notices.ts: ${notices.length} packages, ${texts.length} licence texts`)
if (!existsSync(join(root, 'node_modules/dexie/NOTICE'))) console.warn('dexie NOTICE missing')
