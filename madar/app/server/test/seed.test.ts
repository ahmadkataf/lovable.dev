// Seed invariants: the ten-school demo data that the director sees (schema.sql + seed.sql in an in-memory SQLite).
import { describe, expect, it } from 'vitest'
import { resolve } from 'node:path'
import { readFileSync, statSync } from 'node:fs'
import { fakeD1 } from './d1'
import { reportDate, weekday } from '../src/util'
import { threeDayAbsences } from '../src/stats'
import { ensureSubstitutions } from '../src/substitute'
import { directorateOverview } from '../src/routes/directorate'

const SCHEMA = resolve(__dirname, '../schema.sql'), SEED = resolve(__dirname, '../seed.sql')
const db = fakeD1([SCHEMA, SEED])
const REPORT = reportDate()
const one = <T = Record<string, unknown>>(sql: string, ...p: unknown[]) => db.raw.prepare(sql).get(...(p as never[])) as T
const all = <T = Record<string, unknown>>(sql: string, ...p: unknown[]) => db.raw.prepare(sql).all(...(p as never[])) as T[]
const n = (sql: string, ...p: unknown[]) => Number(one<{ n: number }>(sql, ...p).n)
const env = { WEEKLY_CAP: '28' }

const SCHOOL_NAMES = ['مدرسة درعا النموذجية', 'مدرسة إزرع الأولى', 'مدرسة طفس الثانية', 'مدرسة نوى الأولى', 'مدرسة الصنمين المختلطة', 'مدرسة جاسم الثانية',
  'مدرسة الحراك الأولى', 'مدرسة بصرى الشام الأولى', 'مدرسة داعل', 'مدرسة المزيريب']

describe('seed: the ten-school pilot', () => {
  it('seed.sql stays under 1.5 MB, is generated, and applies a second time without adding rows', () => {
    expect(statSync(SEED).size).toBeLessThan(1.5 * 1024 * 1024)
    const sql = readFileSync(SEED, 'utf8')
    expect(sql).toContain('GENERATED by scripts/gen-seed.mjs')
    expect(sql).not.toMatch(/ًا/)      // tanwīn is written after the alif («صباحاً», not «صباحًا»)
    expect(sql).not.toContain('ـ')     // no tatweel
    const before = ['users', 'students', 'timetable', 'attendance', 'absences', 'substitutions', 'notifications', 'audit_log', 'homework'].map(t => n(`SELECT COUNT(*) AS n FROM ${t}`))
    db.raw.exec(sql)
    const after = ['users', 'students', 'timetable', 'attendance', 'absences', 'substitutions', 'notifications', 'audit_log', 'homework'].map(t => n(`SELECT COUNT(*) AS n FROM ${t}`))
    expect(after).toEqual(before)
    expect(one("SELECT COUNT(*) AS n FROM sqlite_master WHERE name = 'demo_days'").n).toBe(0)   // the helper table is dropped again
  })

  it('ten schools of the governorate, each with 200–600 students, 10–20 teachers, a principal and a school phone', () => {
    const schools = all<{ id: number; name: string; complex: string; principal: string; phone: string; students: number; teachers: number; sections: number }>(`
      SELECT sc.id, sc.name, sc.complex, sc.principal, sc.phone,
             COALESCE(NULLIF((SELECT COUNT(*) FROM students st JOIN sections sec ON sec.id = st.section_id WHERE sec.school_id = sc.id), 0), sc.enrolled) AS students,
             (SELECT COUNT(*) FROM users u WHERE u.role = 'teacher' AND u.school_id = sc.id) AS teachers,
             (SELECT COUNT(*) FROM sections WHERE school_id = sc.id) AS sections
      FROM schools sc ORDER BY sc.id`)
    expect(schools.map(s => s.name)).toEqual(SCHOOL_NAMES)
    expect(schools.map(s => s.complex)).toEqual(['درعا المدينة', 'إزرع', 'طفس', 'نوى', 'الصنمين', 'جاسم', 'الحراك', 'بصرى الشام', 'داعل', 'المزيريب'])
    for (const s of schools) {
      expect(s.students).toBeGreaterThanOrEqual(200)
      expect(s.students).toBeLessThanOrEqual(600)
      expect(s.teachers).toBeGreaterThanOrEqual(10)
      expect(s.teachers).toBeLessThanOrEqual(20)
      expect(s.sections).toBeGreaterThanOrEqual(8)
      expect(s.principal).toMatch(/^\S+ \S+( \S+)?$/)
      expect(s.phone).toMatch(/^0955\d{6}$/)
      expect(n("SELECT COUNT(*) AS n FROM users WHERE role = 'school' AND school_id = ?", s.id)).toBe(1)
    }
    // pupils (and their attendance rows) exist only in the three demo schools; the others carry enrolment + daily summaries
    expect(n('SELECT COUNT(*) AS n FROM students')).toBeGreaterThan(700)
    expect(n('SELECT COUNT(*) AS n FROM sections WHERE school_id <= 3 AND id NOT IN (SELECT DISTINCT section_id FROM students)')).toBe(0)
    expect(n('SELECT COUNT(*) AS n FROM students st JOIN sections sec ON sec.id = st.section_id WHERE sec.school_id > 3')).toBe(0)
    // sections hold 25–33 students (the five round-1 sections 28)
    expect(one('SELECT MIN(c) AS mn, MAX(c) AS mx FROM (SELECT COUNT(*) AS c FROM students GROUP BY section_id)')).toEqual({ mn: 25, mx: 33 })
  })

  it('every section has a full Sun–Thu week with the subject quotas, and no teacher is in two places at once', () => {
    expect(all('SELECT section_id FROM timetable GROUP BY section_id HAVING COUNT(*) <> 30')).toEqual([])
    expect(all('SELECT teacher_id, day, period FROM timetable GROUP BY teacher_id, day, period HAVING COUNT(*) > 1')).toEqual([])
    expect(all('SELECT section_id, subject_id, COUNT(*) AS c FROM timetable GROUP BY section_id, subject_id HAVING c NOT IN (4, 5, 6, 7)')).toEqual([])
    expect(n('SELECT COUNT(*) AS n FROM sections WHERE id NOT IN (SELECT DISTINCT section_id FROM timetable)')).toBe(0)
    // the pitch anchors
    expect(all<{ teacher_id: number }>('SELECT teacher_id FROM timetable WHERE section_id = 2 AND day = 4 ORDER BY period').map(r => r.teacher_id)).toEqual([14, 11, 12, 16, 15, 17])
    expect(n('SELECT COUNT(*) AS n FROM timetable WHERE teacher_id = 11 AND day = 4 AND period = 5')).toBe(0)   // سامر free Thu P5
    expect(n('SELECT COUNT(*) AS n FROM timetable WHERE teacher_id = 13 AND day = 4 AND period = 3')).toBe(0)   // ماهر free Thu P3
    expect(n('SELECT COUNT(*) AS n FROM timetable WHERE teacher_id = 13')).toBeGreaterThan(12)                 // …and a real load
    // every weekday رنا has a period in which ماهر is free (the seeded approval works whatever day the reseed runs)
    for (let d = 0; d < 5; d++) expect(n(`SELECT COUNT(*) AS n FROM timetable t WHERE t.teacher_id = 12 AND t.day = ?
      AND NOT EXISTS (SELECT 1 FROM timetable m WHERE m.teacher_id = 13 AND m.day = t.day AND m.period = t.period)`, d)).toBeGreaterThan(0)
    // no teacher is loaded beyond the weekly cap
    expect(n('SELECT COUNT(*) AS n FROM (SELECT teacher_id FROM timetable GROUP BY teacher_id HAVING COUNT(*) > 28)')).toBe(0)
  })

  it('the demo codes exist with their stories', () => {
    for (const code of ['DIR-DARAA', 'SCH-1', 'SCH-2', 'SCH-3', 'SCH-10', 'T-SAMER', 'T-RANA', 'T-MAHER', 'T-HIBA', 'T-KHALED', 'T-LINA', 'T-OMAR', 'S-LAYAN', 'S-5B-01', 'S-5A-12', 'P-KHALED', 'P-1', 'P-24', 'T-B-AHMAD', 'T-C-RAHAF'])
      expect(n('SELECT COUNT(*) AS n FROM users WHERE code = ?', code), code).toBe(1)
    expect(n('SELECT COUNT(*) AS n FROM users u1 JOIN users u2 ON u1.code = u2.code AND u1.id <> u2.id')).toBe(0)
    // the parent's two children, the demo student, the homework due in three days
    expect(all<{ name: string; label: string }>(`SELECT u.name, sec.label FROM students st JOIN users u ON u.id = st.user_id JOIN sections sec ON sec.id = st.section_id
      WHERE st.guardian_user_id = (SELECT id FROM users WHERE code = 'P-KHALED') ORDER BY sec.grade`)).toEqual([{ name: 'محمد خالد', label: 'الخامس (ب)' }, { name: 'سارة خالد', label: 'السادس (أ)' }])
    expect(one(`SELECT sec.label FROM students st JOIN users u ON u.id = st.user_id JOIN sections sec ON sec.id = st.section_id WHERE u.code = 'S-LAYAN'`)).toEqual({ label: 'الخامس (ب)' })
    expect(one("SELECT title, due_date, section_id FROM homework WHERE id = 1")).toEqual({ title: 'تمارين الكسور العشرية ص ٤٢', due_date: addDays(REPORT, 3), section_id: 2 })
    // رنا is absent on the demo day and ماهر is the approved substitute for one of her periods; a second absence has its last two periods open
    const rana = all<{ status: string; sub: string | null; period: number }>(`SELECT s.status, u.name AS sub, t.period FROM substitutions s JOIN absences a ON a.id = s.absence_id
      JOIN timetable t ON t.id = s.timetable_id LEFT JOIN users u ON u.id = s.substitute_teacher_id WHERE a.teacher_id = 12 AND a.date = ? ORDER BY t.period`, REPORT)
    expect(rana.length).toBe(n('SELECT COUNT(*) AS n FROM timetable WHERE teacher_id = 12 AND day = ?', weekday(REPORT)))
    expect(rana.some(r => r.status === 'approved' && r.sub === 'ماهر عادل')).toBe(true)
    if (weekday(REPORT) === 4) expect(rana.find(r => r.period === 3)).toMatchObject({ status: 'approved', sub: 'ماهر عادل' })   // the pitch's period
    const missing = all<{ teacher_id: number; school_id: number }>(`SELECT a.teacher_id, u.school_id FROM absences a JOIN users u ON u.id = a.teacher_id
      JOIN timetable t ON t.teacher_id = a.teacher_id AND t.day = CAST(strftime('%w', a.date) AS INTEGER)
      WHERE a.date = ? AND NOT EXISTS (SELECT 1 FROM substitutions s WHERE s.absence_id = a.id AND s.timetable_id = t.id) ORDER BY u.school_id`, REPORT)
    expect(missing.map(m => m.school_id)).toEqual([1, 1, 4, 5, 6, 6])   // six live decisions in four schools
    expect(n("SELECT COUNT(*) AS n FROM absences WHERE date = ?", REPORT)).toBe(10)
    expect(n("SELECT COUNT(*) AS n FROM absences a JOIN users u ON u.id = a.teacher_id WHERE a.date = ? AND u.school_id = 1", REPORT)).toBe(2)
    expect(n("SELECT COUNT(*) AS n FROM substitutions s JOIN absences a ON a.id = s.absence_id WHERE a.date = ? AND s.status = 'self_study'", REPORT)).toBeGreaterThan(0)
  })

  it('attendance: the demo day is in progress everywhere but one school; the governorate is at ≈ 90 % with one weak school', () => {
    const perSchool = all<{ school_id: number; recorded: number; attended: number }>(`
      SELECT sec.school_id, COUNT(a.id) AS recorded, COALESCE(SUM(a.status IN ('present', 'late')), 0) AS attended
      FROM sections sec JOIN students st ON st.section_id = sec.id LEFT JOIN attendance a ON a.student_id = st.id AND a.date = ? AND a.period = 1
      GROUP BY sec.school_id
      UNION ALL SELECT sc.id, COALESCE(d.present + d.absent + d.late, 0), COALESCE(d.present + d.late, 0) FROM schools sc LEFT JOIN school_days d ON d.school_id = sc.id AND d.date = ? WHERE sc.id > 3
      ORDER BY 1`, REPORT, REPORT)
    expect(perSchool).toHaveLength(10)
    expect(perSchool.filter(s => s.recorded === 0).map(s => s.school_id)).toEqual([8])
    const pctOf = (s: { recorded: number; attended: number }) => Math.round((100 * s.attended) / s.recorded)
    for (const s of perSchool.filter(s => s.recorded > 0)) { expect(pctOf(s)).toBeGreaterThanOrEqual(76); expect(pctOf(s)).toBeLessThanOrEqual(96) }
    expect(pctOf(perSchool.find(s => s.school_id === 6)!)).toBeLessThanOrEqual(84)
    const gov = (100 * perSchool.reduce((n, s) => n + s.attended, 0)) / perSchool.reduce((n, s) => n + s.recorded, 0)
    expect(gov).toBeGreaterThanOrEqual(86)
    expect(gov).toBeLessThanOrEqual(93)
    // the demo day has periods 1–2 (unconfirmed); the four school days before it keep the first period only, confirmed
    expect(one('SELECT MAX(period) AS p, MAX(confirmed) AS c FROM attendance WHERE date = ?', REPORT)).toEqual({ p: 2, c: 0 })
    expect(all<{ date: string; p: number }>('SELECT date, MAX(period) AS p FROM attendance WHERE date < ? GROUP BY date', REPORT).map(r => r.p)).toEqual([1, 1, 1, 1, 1, 1])
    expect(n('SELECT COUNT(*) AS n FROM attendance WHERE date < ? AND (confirmed <> 1)', REPORT)).toBe(0)
    expect(all<{ d: string }>('SELECT DISTINCT date AS d FROM attendance UNION SELECT DISTINCT date FROM school_days').every(r => weekday(r.d) <= 4)).toBe(true)
    expect(one(`SELECT MIN(created_at) AS t FROM attendance WHERE date = ?`, REPORT)).toEqual({ t: `${REPORT} 04:42:00` })   // 07:42 Damascus
    // the whole seed stays small enough for a daily reseed on the free tier
    expect(n('SELECT COUNT(*) AS n FROM attendance')).toBeLessThan(7000)
  })

  it('exactly one three-day absence streak: يزن عماد of الخامس (أ)', async () => {
    const three = await threeDayAbsences(db, REPORT, null)
    expect(three.map(t => [t.student_name, t.section_label, t.school])).toEqual([['يزن عماد', 'الخامس (أ)', 'مدرسة درعا النموذجية']])
    expect(three[0].days).toBeGreaterThanOrEqual(3)
    // no accidental streak hides in the hash: two-day streaks are rare, three-day ones impossible
    expect(n(`SELECT COUNT(*) AS n FROM (SELECT student_id FROM attendance WHERE period = 1 AND status = 'absent' GROUP BY student_id HAVING COUNT(*) >= 3)`)).toBe(1)
  })

  it('people: Syrian names with compound given names whole, synthetic phones, about half of the guardians with the app', () => {
    const names = all<{ name: string }>("SELECT name FROM users WHERE role IN ('student', 'teacher', 'parent')").map(r => r.name)
    expect(names.every(x => /^[؀-ۿ\s]+$/.test(x) && x.trim().split(/\s+/).length >= 2)).toBe(true)
    expect(names.some(x => x.startsWith('عبد الرحمن '))).toBe(true)
    expect(names.every(x => !/^(الرحمن|الله|الكريم|العزيز|الدين)\b/.test(x))).toBe(true)
    expect(n("SELECT COUNT(*) AS n FROM users WHERE role = 'parent' AND name LIKE 'الرحمن %'")).toBe(0)   // a guardian is named after the father, never after half a compound name
    expect(all<{ phone: string }>("SELECT phone FROM users WHERE role = 'teacher'").every(r => /^0930\d{6}$/.test(r.phone))).toBe(true)
    expect(all<{ phone: string }>("SELECT phone FROM users WHERE role = 'parent'").every(r => /^0940\d{6}$/.test(r.phone))).toBe(true)
    expect(n("SELECT COUNT(*) AS n FROM users WHERE role IN ('student', 'school', 'directorate') AND phone IS NOT NULL")).toBe(0)
    const guardians = n("SELECT COUNT(*) AS n FROM users WHERE role = 'parent'")
    const withApp = n("SELECT COUNT(*) AS n FROM users u WHERE role = 'parent' AND EXISTS (SELECT 1 FROM audit_log al WHERE al.user_id = u.id AND al.action = 'login')")
    expect(withApp / guardians).toBeGreaterThan(0.45)
    expect(withApp / guardians).toBeLessThan(0.65)
    expect(n("SELECT COUNT(*) AS n FROM students WHERE guardian_user_id IS NOT NULL") / n('SELECT COUNT(*) AS n FROM students')).toBeGreaterThan(0.6)
    // the demo parent has opened the app (his notices stay in-app)
    expect(n("SELECT COUNT(*) AS n FROM audit_log WHERE action = 'login' AND user_id = 409")).toBe(1)
  })

  it('after the engine fills the pending periods: one or two uncovered per affected school, ≈ 85 % coverage, six alerts', async () => {
    await ensureSubstitutions(db, env, REPORT, null)
    const stillMissing = n(`SELECT COUNT(*) AS n FROM absences a JOIN timetable t ON t.teacher_id = a.teacher_id AND t.day = CAST(strftime('%w', a.date) AS INTEGER)
      WHERE a.date = ? AND NOT EXISTS (SELECT 1 FROM substitutions s WHERE s.absence_id = a.id AND s.timetable_id = t.id)`, REPORT)
    expect(stillMissing).toBe(0)
    const suggested = all<{ candidates: string }>("SELECT s.candidates FROM substitutions s JOIN absences a ON a.id = s.absence_id WHERE a.date = ? AND s.status = 'suggested'", REPORT)
    expect(suggested).toHaveLength(6)
    expect(suggested.every(r => (JSON.parse(r.candidates) as unknown[]).length > 0)).toBe(true)   // every live decision has ranked candidates
    const { schools, alerts } = await directorateOverview(db, env, REPORT)
    const affected = schools.reduce((x, s) => x + s.affected_periods, 0), covered = schools.reduce((x, s) => x + s.covered_periods, 0)
    expect(affected).toBeGreaterThan(30)
    expect(Math.round((100 * covered) / affected)).toBeGreaterThanOrEqual(80)
    expect(Math.round((100 * covered) / affected)).toBeLessThanOrEqual(92)
    expect(schools.map(s => s.uncovered_periods)).toEqual([2, 0, 0, 1, 1, 2, 0, 0, 0, 0])
    expect(alerts.map(a => a.kind).sort()).toEqual(['no_attendance', 'three_days', 'uncovered', 'uncovered', 'uncovered', 'uncovered'])
    // the overview stored the alerts for the directorate user, once
    expect(n("SELECT COUNT(*) AS n FROM notifications WHERE user_id = 1 AND kind IN ('no_attendance', 'uncovered', 'three_days')")).toBe(6)
    await directorateOverview(db, env, REPORT)
    expect(n("SELECT COUNT(*) AS n FROM notifications WHERE user_id = 1 AND kind IN ('no_attendance', 'uncovered', 'three_days')")).toBe(6)
  })
})

function addDays(date: string, days: number): string {
  const d = new Date(date + 'T00:00:00Z'); d.setUTCDate(d.getUTCDate() + days); return d.toISOString().slice(0, 10)
}
