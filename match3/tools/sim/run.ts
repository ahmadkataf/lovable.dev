/**
 * Level simulator.
 *
 *   node tools/sim/run.ts --levels 1-120 --games 300 --bot casual
 *
 * Prints one row per level: win rate, mean moves left when winning, p10 / p50 / p90 of the final
 * score of the wins (end bonus included), automatic shuffles per game, and a flag when the level
 * is outside its target band (bands are defined for the casual bot; for the expert bot the flag
 * marks levels it wins less than 60 % of the time).
 *
 * Options:
 *   --levels  "1-120", "7", "1-5,10,20-25"      (default: all)
 *   --games   games per level                    (default 300)
 *   --bot     random | casual | expert           (default casual)
 *   --seed    base seed                          (default 1)
 *   --workers worker threads, at most 3          (default 3)
 *   --report  also run the expert bot and write the full table to tools/sim/REPORT.md
 *             (--expert-games sets its sample size, default 60)
 */
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { LEVELS } from '../../src/levels/index.ts';
import type { LevelDef } from '../../src/engine/index.ts';
import { BOT_KINDS, type BotKind } from './bot.ts';
import { runJobs, workerCount } from './pool.ts';
import { EXPERT_MIN, bandFlag, bandFor, describeGoals, parseRange, seedFor, summarise, type JobResult, type LevelStats, type SimJob } from './stats.ts';

interface Args {
  levels: number[];
  games: number;
  bot: BotKind;
  seed: number;
  workers: number;
  report: boolean;
  expertGames: number;
}

function parseArgs(argv: readonly string[]): Args {
  const args: Args = { levels: LEVELS.map((l) => l.id), games: 300, bot: 'casual', seed: 1, workers: workerCount(), report: false, expertGames: 60 };
  for (let k = 0; k < argv.length; k++) {
    const flag = argv[k]!;
    const value = (): string => {
      const v = argv[++k];
      if (v === undefined) throw new Error(`${flag} needs a value`);
      return v;
    };
    switch (flag) {
      case '--levels':
        args.levels = parseRange(value(), LEVELS.length);
        break;
      case '--games':
        args.games = Math.max(1, Math.floor(Number(value())));
        break;
      case '--bot': {
        const bot = value() as BotKind;
        if (BOT_KINDS.indexOf(bot) < 0) throw new Error(`unknown bot "${bot}" (use ${BOT_KINDS.join(', ')})`);
        args.bot = bot;
        break;
      }
      case '--seed':
        args.seed = Math.floor(Number(value()));
        break;
      case '--workers':
        args.workers = workerCount(Number(value()));
        break;
      case '--report':
        args.report = true;
        break;
      case '--expert-games':
        args.expertGames = Math.max(1, Math.floor(Number(value())));
        break;
      default:
        throw new Error(`unknown option ${flag}`);
    }
  }
  if (!Number.isFinite(args.games) || !Number.isFinite(args.seed)) throw new Error('--games and --seed need numbers');
  return args;
}

function levelById(id: number): LevelDef {
  const level = LEVELS[id - 1];
  if (!level || level.id !== id) throw new Error(`no level ${id}`);
  return level;
}

function pad(text: string | number, width: number): string {
  const s = String(text);
  return s.length >= width ? s : ' '.repeat(width - s.length) + s;
}

function flagFor(level: LevelDef, bot: BotKind, stats: LevelStats): string {
  if (bot === 'casual') return bandFlag(level, stats.winRate);
  if (bot === 'expert') return stats.winRate < EXPERT_MIN ? `LOW −${(EXPERT_MIN - stats.winRate).toFixed(1)}` : '';
  return '';
}

function printTable(levels: readonly LevelDef[], bot: BotKind, stats: readonly LevelStats[]): number {
  console.log(` lvl  ${pad('band', 13)}  ${pad('win%', 6)}  ${pad('left', 5)}  ${pad('p10', 6)} ${pad('p50', 6)} ${pad('p90', 6)}  ${pad('shuf/g', 6)}  flag`);
  let flagged = 0;
  levels.forEach((level, k) => {
    const s = stats[k]!;
    const flag = flagFor(level, bot, s);
    if (flag !== '') flagged++;
    const band = bot === 'expert' ? `≥${EXPERT_MIN}` : bandFor(level).label;
    console.log(
      `${pad(level.id, 4)}  ${pad(band, 13)}  ${pad(s.winRate.toFixed(1), 6)}  ${pad(s.movesLeft.toFixed(1), 5)}  ${pad(s.p10, 6)} ${pad(s.p50, 6)} ${pad(s.p90, 6)}  ${pad(s.shufflesPerGame.toFixed(2), 6)}  ${flag}${s.deadBoards > 0 ? ` dead×${s.deadBoards}` : ''}`,
    );
  });
  return flagged;
}

function reportMarkdown(levels: readonly LevelDef[], games: number, expertGames: number, casual: readonly LevelStats[], expert: readonly LevelStats[]): string {
  const lines: string[] = [];
  lines.push('# Level balance report');
  lines.push('');
  lines.push(`Generated by \`node tools/sim/run.ts --report\` — casual bot ${games} games per level, expert bot ${expertGames} games per level.`);
  lines.push('Scores are the final scores of winning games (end bonus included). Flags: casual win rate outside the band, or expert below 60 %.');
  lines.push('');
  lines.push('| lvl | mark | colours | moves | goals | band | casual win % | expert win % | moves left | p10 | p50 | p90 | stars | shuffles/game | flag |');
  lines.push('|---:|---|---:|---:|---|---|---:|---:|---:|---:|---:|---:|---|---:|---|');
  let inBand = 0;
  let expertOk = 0;
  levels.forEach((level, k) => {
    const c = casual[k]!;
    const e = expert[k]!;
    const flags: string[] = [];
    const bf = bandFlag(level, c.winRate);
    if (bf !== '') flags.push(`casual ${bf}`);
    else inBand++;
    if (e.winRate < EXPERT_MIN) flags.push(`expert ${e.winRate.toFixed(0)}`);
    else expertOk++;
    const mark = [level.hard ? 'hard' : '', level.tutorial !== undefined ? `tut:${level.tutorial}` : ''].filter((s) => s !== '').join(' ');
    lines.push(
      `| ${level.id} | ${mark} | ${level.colors} | ${level.moves} | ${describeGoals(level)} | ${bandFor(level).label} | ${c.winRate.toFixed(1)} | ${e.winRate.toFixed(0)} | ${c.movesLeft.toFixed(1)} | ${c.p10} | ${c.p50} | ${c.p90} | ${level.stars.join(' / ')} | ${c.shufflesPerGame.toFixed(2)} | ${flags.join(', ')} |`,
    );
  });
  lines.push('');
  lines.push(`Summary: ${inBand} of ${levels.length} levels inside their casual band; expert bot ≥ ${EXPERT_MIN} % on ${expertOk} of ${levels.length}.`);
  lines.push('');
  return lines.join('\n');
}

async function main(): Promise<void> {
  const args = parseArgs(process.argv.slice(2));
  const levels = args.levels.map(levelById);
  const jobsFor = (bot: BotKind, games: number): SimJob[] => levels.map((level) => ({ level, bot, games, seed: seedFor(level.id, args.seed) }));
  const progress = (label: string) => (_r: JobResult, done: number) => {
    if (process.stderr.isTTY) process.stderr.write(`\r${label}: ${done}/${levels.length} levels`);
  };

  const started = Date.now();
  const bot: BotKind = args.report ? 'casual' : args.bot;
  console.log(`${bot} bot · ${args.games} games per level · ${levels.length} levels · seed ${args.seed} · ${args.workers} worker(s)`);
  const results = await runJobs(jobsFor(bot, args.games), args.workers, progress(bot));
  if (process.stderr.isTTY) process.stderr.write('\r\x1b[K');
  const stats = results.map(summarise);
  const flagged = printTable(levels, bot, stats);
  const mean = stats.reduce((sum, s) => sum + s.winRate, 0) / Math.max(1, stats.length);
  console.log(`\n${levels.length - flagged}/${levels.length} levels in band · mean win rate ${mean.toFixed(1)} % · ${((Date.now() - started) / 1000).toFixed(1)} s`);

  if (args.report) {
    const t1 = Date.now();
    console.log(`\nexpert bot · ${args.expertGames} games per level`);
    const expertResults = await runJobs(jobsFor('expert', args.expertGames), args.workers, progress('expert'));
    if (process.stderr.isTTY) process.stderr.write('\r\x1b[K');
    const expertStats = expertResults.map(summarise);
    const weak = printTable(levels, 'expert', expertStats);
    console.log(`\n${levels.length - weak}/${levels.length} levels with expert ≥ ${EXPERT_MIN} % · ${((Date.now() - t1) / 1000).toFixed(1)} s`);
    const file = fileURLToPath(new URL('./REPORT.md', import.meta.url));
    writeFileSync(file, reportMarkdown(levels, args.games, args.expertGames, stats, expertStats));
    console.log(`wrote ${file}`);
  }
}

main().catch((err) => {
  console.error(err instanceof Error ? err.message : err);
  process.exit(1);
});
