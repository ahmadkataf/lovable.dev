// Splits a book sold online into what ships inside the app and what only the server hands out.
//   node scripts/split-online.mjs g12
// generated/<book>/            the app's data: the free unit and the first exam in full, the rest as outlines
// generated/<book>/public/     the app's static files, with the free unit's audio only
// server/content/<book>/       the whole book (full.json) and all its audio, served after activation
import { build } from 'esbuild'
import crypto from 'crypto'
import fs from 'fs'
import path from 'path'
import { pathToFileURL } from 'url'

const BOOK = process.argv[2] || 'g12'
const cache = path.resolve('node_modules/.cache')
fs.mkdirSync(cache, { recursive: true })
for (const [entry, out] of [[`src/books/${BOOK}/index.ts`, 'online-book.mjs'], ['src/engine/generator.ts', 'online-gen.mjs']]) {
  await build({ entryPoints: [entry], bundle: true, format: 'esm', platform: 'node', outfile: `${cache}/${out}`, logLevel: 'error' })
}
const { book, modules, exams } = await import(pathToFileURL(`${cache}/online-book.mjs`).href + `?t=${Date.now()}`)
const { lessonsForUnit } = await import(pathToFileURL(`${cache}/online-gen.mjs`).href + `?t=${Date.now()}`)

const freeUnit = modules[0].units[0].id
const FREE_AUDIO = [freeUnit]

// a locked unit keeps what the path and the menus show: its title, pages and lesson list
const outlineUnit = u => ({
  id: u.id, number: u.number, module: u.module, title: u.title, titleAr: u.titleAr, pages: u.pages, emoji: u.emoji, planAr: u.planAr,
  vocab: [], sentences: [],
  reading: { title: u.reading.title, paragraphs: [], paragraphsAr: [], questions: [] },
  grammar: { name: u.grammar.name, nameAr: u.grammar.nameAr, ruleEn: [], ruleAr: [], examples: [], exercises: [] },
  ...(u.workbook ? { workbook: { pages: u.workbook.pages, readings: [], exercises: [] } } : {}),
  outline: { lessons: lessonsForUnit(u).map(({ unitId, ...l }) => l), vocab: u.vocab.length },
})
const outlineReview = r => r && { title: r.title, titleAr: r.titleAr, pages: r.pages, exercises: [] }
const free = {
  modules: modules.map(m => ({
    ...m,
    units: m.units.map(u => (u.id === freeUnit ? u : outlineUnit(u))),
    review: outlineReview(m.review),
    progressTest: outlineReview(m.progressTest),
    project: m.project && { title: m.project.title, steps: [] },
  })),
  exams: exams.map((e, i) => (i === 0 ? e : { ...e, sections: [] })),
}
const full = { modules, exams }
const fullJson = JSON.stringify(full)
const pub = `public/${BOOK}`
const indexJson = fs.readFileSync(`${pub}/audio/index.json`, 'utf8')
// the audio is part of the version too, so that phones drop the recordings they cached when they change
const version = crypto.createHash('sha256').update(fullJson).update(indexJson).digest('hex').slice(0, 12)

// the app
const gen = `generated/${BOOK}`
fs.rmSync(gen, { recursive: true, force: true })
fs.mkdirSync(`${gen}/public/audio`, { recursive: true })
fs.writeFileSync(`${gen}/free.json`, JSON.stringify({ ...free, version }))
fs.writeFileSync(`${gen}/index.ts`, `// Generated by scripts/split-online.mjs — do not edit.
import type { BookMeta, Exam, Module } from '../../src/engine/types'
import meta from '../../src/books/${BOOK}/book.json'
import data from './free.json'
export const book: BookMeta = meta
export const modules = data.modules as unknown as Module[]
export const exams = data.exams as unknown as Exam[]
export const contentVersion: string = data.version
`)
for (const f of fs.readdirSync(pub)) if (f !== 'audio') fs.cpSync(`${pub}/${f}`, `${gen}/public/${f}`, { recursive: true })
const index = JSON.parse(indexJson)
// a unit's recordings are one file (u1) or, cut into short pieces, several (u1c0, u1c1, …)
const freeFiles = Object.keys(index.groups).filter(g => FREE_AUDIO.some(u => g === u || new RegExp(`^${u}c\\d+$`).test(g)))
fs.writeFileSync(`${gen}/public/audio/index.json`, JSON.stringify({ ...index, groups: Object.fromEntries(freeFiles.map(g => [g, index.groups[g]])) }))
for (const g of freeFiles) fs.copyFileSync(`${pub}/audio/${g}.mp3`, `${gen}/public/audio/${g}.mp3`)

// the server
const srv = `server/content/${BOOK}`
fs.rmSync(srv, { recursive: true, force: true })
fs.mkdirSync(`${srv}/audio`, { recursive: true })
fs.writeFileSync(`${srv}/full.json`, fullJson)
fs.writeFileSync(`${srv}/version.json`, JSON.stringify({ version }))
for (const f of fs.readdirSync(`${pub}/audio`)) fs.copyFileSync(`${pub}/audio/${f}`, `${srv}/audio/${f}`)

const size = f => (fs.statSync(f).size / 1024).toFixed(0) + ' KB'
console.log(`${BOOK}: version ${version}; app data ${size(`${gen}/free.json`)} (full book ${size(`${srv}/full.json`)}); free audio ${FREE_AUDIO.join(',')} (${freeFiles.length} files)`)
